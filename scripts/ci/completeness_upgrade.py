# A check that covers only part of a ledger row names a *step* id, `ROW/step`,
# and never the row itself. Naming the row would let the row inherit a ceiling
# from a component, which is the `A4-STD-01` sub-step loophole: exhaustive atoms
# standing in for an end-to-end claim that was only sampled.


# --------------------------------------------------------------------------
# Generalized-expression constructors (JSON shape of tools/regex_cert.py)
# --------------------------------------------------------------------------

EMPTY = {"op": "empty"}
EPS = {"op": "eps"}


def lit(x: str) -> dict:
    return {"op": "letter", "value": x}


def cat(*args: dict) -> dict:
    return {"op": "concat", "args": list(args)} if args else EPS


def alt(*args: dict) -> dict:
    return {"op": "union", "args": list(args)}


def compl(arg: dict) -> dict:
    return {"op": "compl", "arg": arg}


def star(arg: dict) -> dict:
    return {"op": "star", "arg": arg}


UNIV = compl(EMPTY)  # Sigma*, star height 0


def avoid(x: str) -> dict:
    """Words containing no `x`, i.e. the star-free language usually written x'*.

    Written with complement so that it costs star height ZERO. Writing it as a
    star instead is what pushes these constructions to height 2.
    """
    return compl(cat(UNIV, lit(x), UNIV))


def inter(*args: dict) -> dict:
    return compl(alt(*[compl(a) for a in args]))


def cayley_dfa(alphabet, images, mul, ident, accept=None) -> DFA:
    """Cayley automaton of the group generated by `images`, from the identity."""
    states = {ident}
    frontier = deque([ident])
    transition = {}
    while frontier:
        g = frontier.popleft()
        for x in alphabet:
            h = mul(g, images[x])
            transition[(g, x)] = h
            if h not in states:
                states.add(h)
                frontier.append(h)
    acc = frozenset({ident} if accept is None else accept)
    dfa = DFA(tuple(alphabet), frozenset(states), ident, acc, transition)
    dfa.validate()
    return dfa


def product_universe(left: DFA, right: DFA) -> int:
    """How many product states an equivalence check actually visits.

    Counted rather than estimated.  `tools.verdict.exhaustive` requires the size
    of the object traversed, and a traversal that reports a size it did not
    count is the same kind of unchecked claim the ledger exists to stop.
    """
    start = (left.start, right.start)
    seen = {start}
    frontier = deque([start])
    while frontier:
        pair = frontier.popleft()
        for symbol in left.alphabet:
            nxt = (left.step(pair[0], symbol), right.step(pair[1], symbol))
            if nxt not in seen:
                seen.add(nxt)
                frontier.append(nxt)
    return len(seen)


def transition_monoid(machine: DFA) -> list[tuple[Hashable, ...]]:
    """Every transformation of the state set induced by a word.

    Finite because the state set is, and generated from the letters by closure
    under composition -- the standard construction, computed rather than cited
    so that the aperiodicity test below has something to test.
    """
    order = sorted(machine.states, key=repr)
    index = {state: i for i, state in enumerate(order)}
    generators = [
        tuple(index[machine.step(state, letter)] for state in order)
        for letter in machine.alphabet
    ]
    identity = tuple(range(len(order)))
    elements = {identity}
    frontier = deque([identity])
    while frontier:
        element = frontier.popleft()
        for generator in generators:
            product = tuple(generator[i] for i in element)
            if product not in elements:
                elements.add(product)
                frontier.append(product)
    return sorted(elements)


def aperiodic_witness(machine: DFA) -> tuple[Hashable, ...] | None:
    """An element with `m^n != m^(n+1)` for all `n`, or `None` if aperiodic.

    A language is star-free -- equivalently of generalized star-height zero --
    exactly when its syntactic monoid is aperiodic (Schutzenberger 1965).  So a
    witness here is a *lower* bound: it proves the height is at least one, which
    is the half of "exactly one" that an equivalence check cannot give.
    """
    elements = transition_monoid(machine)
    size = len(elements)
    for element in elements:
        power, seen = element, {element}
        stable = False
        for _ in range(size + 1):
            nxt = tuple(element[i] for i in power)
            if nxt == power:
                stable = True
                break
            power = nxt
            seen.add(power)
        if not stable:
            return element
    return None


def decide_equivalence(
    name: str,
    claim_ids,
    *,
    expr: dict,
    alphabet: Sequence[str],
    target: DFA,
    height: int,
    controls: Sequence[tuple[str, str, dict]],
    covers: str = "step",
    rationale: str = "",
) -> "object":
    """Prove `expr` denotes exactly `target`'s language, at star height <= `height`.

    `controls` are deliberately false variants of the *expression*, each with a
    description of what was broken in the claim's own vocabulary.  They are part
    of the check rather than a separate line of output: an equivalence checker
    that accepts a broken expression has not proved anything about the correct
    one, so the two facts belong to the same verdict.
    """
    parsed = parse_regex(expr, alphabet)
    got_height = parsed.star_height()
    compiled = compile_regex(parsed, alphabet)
    witness = equivalence_witness(compiled, target)

    fired = []
    for control_name, mutation, broken in controls:
        broken_witness = equivalence_witness(compile_regex(parse_regex(broken, alphabet), alphabet), target)
        fired.append(Control(control_name, mutation, rejected=broken_witness is not None))

    if got_height > height:
        detail = f"star height {got_height} exceeds the claimed {height}"
        passed = False
    elif witness is not None:
        detail = f"NOT equivalent; shortest distinguishing word {''.join(witness)!r}"
        passed = False
    else:
        detail = (
            f"exact DFA equivalence by product reachability "
            f"(star height {got_height} <= {height}; target {len(target.states)} states)"
        )
        passed = True

    return RUN.add(
        exhaustive(
            name,
            claim_ids,
            passed=passed,
            universe=product_universe(compiled, target),
            detail=detail,
            controls=fired,
            covers=covers,
            rationale=rationale,
        )
    )


