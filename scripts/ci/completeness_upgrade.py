#!/usr/bin/env python3
"""Turn sampled checks into decided ones, and emit a machine-readable verdict.

The 2026-07-25 completeness audit found ledger rows whose final step was
bounded-length agreement plus random words.  A sample can refute but never
establish, so those rows were set to `EMPIRICAL`.  This script repairs the
finite proof obligations by reducing each such obligation to a finite object
and traversing it exhaustively, which is what `COMPUTED` now requires.

Three shapes of claim appear:

  * "this height-1 expression denotes exactly that language" - decided by
    compiling the expression to a DFA and running product reachability against
    the target DFA (`tools/regex_cert.py`).  `A5-GEN145-01`.
  * "this closed-form function of the automaton state equals the group element"
    - decided by a BFS over the product of the two automata, checking the
    identity at every reachable pair.  `A4-FULL-01` step [4], `WATOM-45-01`.
  * "this integer identity holds for every word" - decided by
    `tools.verdict.decide_linear_identity`.  `LAAB-04-01`, `THOMAS-D2-02`.

**2026-07-25, second audit.**  The first version of this file certified
`THOMAS-D2-02` with a state machine on `(parse state, d)` where `d` was defined
to be `-1` exactly when `parse == 1`, and the acceptance test asked whether
`d == -1` when `parse == 1`.  It traversed a finite object completely, carried a
negative control that fired, and sampled nothing.  It also mentioned none of
`|w|_a`, `|w|_b`, `#tok`, `#ab` - the quantities the identity is about - so
every coefficient of the identity could be changed without the program
noticing.  The author had solved the arithmetic by hand and coded the answer;
the program confirmed the author.

Both integer identities are therefore now expressed through
`tools.verdict.decide_linear_identity`, which takes the *meaning* of each
quantity and the coefficients, derives the transition function itself, and
requires every single-coefficient perturbation to be rejected.  There is no
longer a place to write a pre-solved defect.  Every check in this file reports
through `tools.verdict`, so the status it can support is computed rather than
described, and lands in `data/verdicts/completeness_upgrade.json`.
"""

