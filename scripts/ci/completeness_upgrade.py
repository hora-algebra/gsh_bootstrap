# WATOM-45-01: the 20 staged-count atoms {w : N_r(w) = h mod 5}
# ==========================================================================
#
# `scripts/research/f20_word_problem.py` check [3b] compares each compiled atom with the
# direct staged count on all 8,191 words of length <= 12. The target is a
# regular language with an obvious 20-state automaton — (b-count mod 4, N_r mod
# 5) — so the comparison can simply be decided instead.


def check_watom() -> None:
    print("\n=== WATOM-45-01: the 20 staged-count atoms N_r = h (mod 5) ===")
    from scripts.research.f20_word_problem import W, AL, compile_dfa, dfa, d_min, height
    from scripts.research.f20_word_problem import equivalence_counterexample

    def staged_target(r: int, h: int):
        """(b-count mod 4, N_r mod 5); `a` counts only while the phase is r."""
        index = {(p, c): p * 5 + c for p in range(4) for c in range(5)}
        transitions = [None] * 20
        for (p, c), i in index.items():
            transitions[i] = {
                "a": index[(p, (c + 1) % 5 if p == r else c)],
                "b": index[((p + 1) % 4, c)],
            }
        accept = [index[(p, h)] for p in range(4)]
        return d_min(dfa(transitions, index[(0, 0)], accept))

    assert set(AL) == {"a", "b"}
    bad = []
    for r in range(4):
        for h in range(5):
            witness = equivalence_counterexample(compile_dfa(W[r][h]), staged_target(r, h))
            if witness is not None:
                bad.append((r, h, witness))

    # Controls on the claim: each atom is compared against the target for the
    # wrong residue, and against the target for the wrong phase. Both are false
    # statements about the same 20 atoms, so a checker that accepts either has
    # not established the correct one.
    missed_residue = [
        (r, h)
        for r in range(4)
        for h in range(5)
        if equivalence_counterexample(compile_dfa(W[r][h]), staged_target(r, (h + 1) % 5))
        is None
    ]
    missed_phase = [
        (r, h)
        for r in range(4)
        for h in range(5)
        if equivalence_counterexample(compile_dfa(W[r][h]), staged_target((r + 1) % 4, h))
        is None
    ]
    equal = RUN.add(
        exhaustive(
            "WATOM-45-01 atoms equal their staged-count DFAs",
            "WATOM-45-01/equality",
            passed=not bad,
            universe=20,
            detail=(
                "all 20 atoms proved equal to their 20-state staged-count DFAs by "
                "complete product reachability"
                if not bad
                else f"{len(bad)} atoms disagree, e.g. {bad[0]}"
            ),
            controls=[
                Control(
                    "residue h -> h+1",
                    "the residue class each atom counts",
                    rejected=not missed_residue,
                ),
                Control(
                    "phase r -> r+1",
                    "the phase at which each atom counts",
                    rejected=not missed_phase,
                ),
            ],
        )
    )

    # The row claims a height, so a height has to be computed. `height` is the
    # syntactic star height of the expression tree; the control is the same
    # measurement on an expression with a star nested inside a star, which must
    # come out above 1 or the measurement is not measuring.
    heights = sorted({height(W[r][h]) for r in range(4) for h in range(5)})
    from scripts.research.f20_word_problem import star as _star, union as _union

    nested = _star(_star(W[0][0]))
    tall = RUN.add(
        exhaustive(
            "WATOM-45-01 atoms have star height 1",
            "WATOM-45-01/height",
            passed=heights == [1],
            universe=20,
            detail=f"syntactic star height of all 20 atoms: {heights}",
            controls=[
                Control(
                    "a star nested inside a star",
                    "the expression whose height is measured",
                    rejected=height(nested) > 1,
                )
            ],
        )
    )
    RUN.add(
        conjunction(
            "WATOM-45-01",
            "WATOM-45-01",
            parts=[equal, tall],
            detail="each atom is the staged-count language, and has star height 1",
            rationale=(
                "the row asserts of the 20 atoms that each *is* the staged-count "
                "language and that each has height <= 1; both are decided, for all 20"
            ),
        )
    )


